// Compatibility export for callers that intentionally use the current Aegis default.
export const SPACEPORT_UPGRADE_BALANCE_V1 = FACTION_SPACEPORT_UPGRADE_BALANCE_V1.aegis;

export function getFactionSpaceportUpgradeBalance(
  factionId: CombatFactionId,
  shipId: string,
  fromLevel: number,
): SpaceportUpgradeBalanceV1Row | null {
  const safeFromLevel = Number.isFinite(fromLevel) ? Math.max(0, Math.floor(fromLevel)) : 0;
  const factionRows = FACTION_SPACEPORT_UPGRADE_BALANCE_V1[factionId] as Partial<Record<ShipId, readonly SpaceportUpgradeBalanceV1Row[]>>;
  return factionRows[shipId as ShipId]?.[safeFromLevel] ?? null;
}
