import type { CombatFactionId } from './factions.ts';
import { SHIP_IDS, type ShipId } from './ids.ts';
import type {
  CombatStats,
  ConstructionDefinition,
  ResourceCost,
  ShipCombatTraits,
} from './types.ts';
import { FACTION_SHIP_BASE_PRODUCTION_TIMES } from './ship-time-rebalanced.ts';

/**
 * Mechanical ship data transcribed from the saved Nemexia pages named in
 * docs/prompts/PHASE_6_CANONICAL_SHIP_DATA_BY_FACTION_PROMPT.md. The
 * construction time is the separate Time Rebalanced `Новое 2%/шт.` column;
 * all other mechanical fields stay sourced from those saved HTML pages.
 *
 * `sourceName` and `sourceFile` are provenance only. Presentation names and
 * assets remain the approved Asterion contract in faction-catalog.ts.
 */
export type FactionShipMechanics = {
  id: ShipId;
  sourceName: string;
  sourceFile: string;
  population: number;
  cost: ResourceCost;
  combat: CombatStats;
  ship?: ShipCombatTraits;
  construction: ConstructionDefinition;
};

type ShipEntry = Omit<FactionShipMechanics, 'sourceFile'> & { sourceFileName: string };

const SOURCE_ROOT = 'saved_pages/312313/Корабли';

function record(
  id: ShipId,
  sourceFileName: string,
  sourceName: string,
  population: number,
  cost: ResourceCost,
  combat: CombatStats,
  time: string,
  requiredShipyardLevel: number,
  requirements: readonly string[],
  ship?: ShipCombatTraits,
): ShipEntry {
  return {
    id,
    sourceName,
    sourceFileName,
    population,
    cost,
    combat,
    ...(ship ? { ship } : {}),
    construction: { time, requiredShipyardLevel, requirements },
  };
}

function defineFaction(
  factionId: CombatFactionId,
  folder: string,
  entries: readonly ShipEntry[],
): Readonly<Record<ShipId, FactionShipMechanics>> {
  const byId = Object.fromEntries(entries.map((entry) => [
    entry.id,
    {
      ...entry,
      sourceFile: `${SOURCE_ROOT}/${folder}/${entry.sourceFileName}`,
      construction: {
        ...entry.construction,
        time: FACTION_SHIP_BASE_PRODUCTION_TIMES[factionId][entry.id],
      },
    },
  ])) as unknown as Record<ShipId, FactionShipMechanics>;
  const missing = SHIP_IDS.filter((id) => !byId[id]);
  if (missing.length > 0) throw new Error(`Incomplete faction ship catalog: ${missing.join(', ')}`);
  return Object.freeze(byId);
}

